-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role BIGINT DEFAULT 1 REFERENCES roles(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. Address Details Table
CREATE TABLE IF NOT EXISTS address_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_name VARCHAR(255),
    phone_number VARCHAR(50),
    street_address VARCHAR(255),
    barangay VARCHAR(255),
    city VARCHAR(255),
    postal_code VARCHAR(20),
    delivery_notes TEXT,
    is_default BOOLEAN DEFAULT FALSE
);

-- 3. Contact Inquiries Table
CREATE TABLE IF NOT EXISTS contact_inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. Product Categories Table
CREATE TABLE IF NOT EXISTS product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

-- Seed Categories (1: Cookie, 2: Cake)
INSERT INTO product_categories (id, category_name) VALUES 
(1, 'Cookie'),
(2, 'Cake')
ON CONFLICT (id) DO UPDATE SET category_name = EXCLUDED.category_name;

-- 5. Products Table
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    category_id BIGINT REFERENCES product_categories(id) ON DELETE SET NULL,
    price NUMERIC(10, 2) DEFAULT 0.00,
    image_url TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Payment Types Table
CREATE TABLE IF NOT EXISTS payment_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(100) NOT NULL UNIQUE
);

-- Seed Payment Types
INSERT INTO payment_types (id, type) VALUES 
(1, 'Cash on Delivery'),
(2, 'Gcash'),
(3, 'Bank')
ON CONFLICT (id) DO UPDATE SET type = EXCLUDED.type;

-- 7. Payment Statuses Table
CREATE TABLE IF NOT EXISTS payment_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_type VARCHAR(100) NOT NULL UNIQUE
);

-- Seed Payment Statuses
INSERT INTO payment_statuses (id, status_type) VALUES 
(1, 'Cash on Delivery'),
(2, 'Paid'),
(3, 'Pending')
ON CONFLICT (id) DO UPDATE SET status_type = EXCLUDED.status_type;

-- 8. Order Statuses Table
CREATE TABLE IF NOT EXISTS order_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(100) NOT NULL UNIQUE
);

-- Seed Order Statuses
INSERT INTO order_status (id, status) VALUES 
(1, 'Pending'),
(2, 'Baking'),
(3, 'Ready for Delivery'),
(4, 'Completed')
ON CONFLICT (id) DO UPDATE SET status = EXCLUDED.status;

-- 9. Orders Table
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(100) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    address_id BIGINT NOT NULL REFERENCES address_details(id),
    status BIGINT NOT NULL DEFAULT 1 REFERENCES order_status(id),
    subtotal NUMERIC(10, 2) NOT NULL,
    delivery_fee NUMERIC(10, 2) DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL,
    payment_method BIGINT NOT NULL REFERENCES payment_types(id),
    payment_status BIGINT NOT NULL REFERENCES payment_statuses(id),
    customer_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. Order Items Table
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity BIGINT NOT NULL DEFAULT 1
);

